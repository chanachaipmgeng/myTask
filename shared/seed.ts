type TicketSeed = Pick<Ticket, 'id' | 'track' | 'type' | 'assigneeId' | 'size' | 'estimateMd' | 'actualMd'> &
  Partial<Ticket>;

function closedMonth(id: string): string {
  const bucket = [...id].reduce((sum, char) => sum + char.charCodeAt(0), 0) % 3;
  return ['2025-08-29', '2025-09-30', '2025-10-31'][bucket];
}

function ticket(seed: TicketSeed): Ticket {
  const draft: Ticket = {
    module: 'Core',
    weekOffset: 0,
    reviewRounds: 1,
    blocker: false,
    reopenCount: 0,
    varianceCode: 'NONE',
    closed: true,
    dodPassed: false,
    inTimeBox: false,
    childTicketsSized: false,
    unplanned: false,
    closedOn: '2025-10-31',
    workingDaysLeft: null,
    note: '',
    ...seed,
  };
  if (!draft.closed) {
    draft.closedOn = null;
  } else if (seed.closedOn === undefined) {
    draft.closedOn = closedMonth(seed.id);
  }
  return decorateSeed(draft, seed);
}

